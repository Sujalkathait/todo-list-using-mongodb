const fs = require('fs');
const path = require('path');
const ejs = require('ejs');

const VIEWS_DIR = path.join(__dirname, '..', 'views');
const OUT_FILE = path.join(__dirname, '..', 'src', 'compiledViews.js');

const TEMPLATE_NAMES = ['navbar', 'list', 'add', 'update'];

function compileTemplateSource(name) {
    const filePath = path.join(VIEWS_DIR, `${name}.ejs`);
    const raw = fs.readFileSync(filePath, 'utf8');
    const tmpl = new ejs.Template(raw, {
        compileDebug: false,
        _with: false,
    });
    tmpl.generateSource();
    return tmpl.source;
}

const compiledBlocks = TEMPLATE_NAMES.map((name) => {
    const source = compileTemplateSource(name);
    return `
function render_${name}(locals = {}) {
    let __output = '';
    function __append(s) {
        if (s !== undefined && s !== null) __output += s;
    }
    const { tasks = [], task = null } = locals;
    ${source}
    return __output;
}`;
}).join('\n');

const output = `// Auto-generated by scripts/build-views.js — do not edit manually.
// Precompiled EJS templates for Cloudflare Workers (no eval / new Function / fs).

function escapeFn(markup) {
    if (markup === undefined || markup === null) return '';
    return String(markup)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&#34;')
        .replace(/'/g, '&#39;');
}

function include(partialName, includeData = {}) {
    const key = partialName.replace(/\\.ejs$/, '');
    const fn = PARTIALS[key];
    if (!fn) throw new Error(\`Unknown EJS partial: \${partialName}\`);
    return fn(includeData);
}

${compiledBlocks}

const PARTIALS = {
    navbar: render_navbar,
};

export const views = {
    list: render_list,
    add: render_add,
    update: render_update,
};
`;

fs.writeFileSync(OUT_FILE, output, 'utf8');
console.log(`Precompiled ${TEMPLATE_NAMES.length} EJS templates to ${OUT_FILE}`);
